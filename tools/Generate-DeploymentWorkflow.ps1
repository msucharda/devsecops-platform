#Requires -Version 7.4
[CmdletBinding()]
param(
    [string] $ModulesPath = (Join-Path $PSScriptRoot '../modules'),
    [string] $OutputPath = (Join-Path $PSScriptRoot '../templates/instance/.github/workflows/deploy.yml'),
    [switch] $Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'PlatformTools.psm1')
$modules = Get-PlatformModuleGraph -ModulesPath $ModulesPath

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Generated by tools/Generate-DeploymentWorkflow.ps1. Do not edit.')
$lines.Add('name: Deploy instance')
$lines.Add('on:')
$lines.Add('  workflow_dispatch:')
$lines.Add('permissions:')
$lines.Add('  contents: read')
$lines.Add('jobs:')
$lines.Add('  select:')
$lines.Add('    name: Select instance modules')
$lines.Add('    runs-on: ubuntu-latest')
$lines.Add('    outputs:')
$lines.Add('      modules: ${{ steps.modules.outputs.modules }}')
$lines.Add('    steps:')
$lines.Add('      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262')
$lines.Add('      - name: Install runtime dependencies')
$lines.Add('        shell: pwsh')
$lines.Add('        run: ./platform/tools/Install-ToolDependencies.ps1')
$lines.Add('      - name: Select modules and prerequisites')
$lines.Add('        id: modules')
$lines.Add('        shell: pwsh')
$lines.Add('        run: ./platform/tools/Select-InstanceModules.ps1 -InstancePath ./instance.yaml -GitHubOutputPath $env:GITHUB_OUTPUT')

foreach ($manifest in $modules.PSBase.Values) {
    $jobId = 'module_' + $manifest.name.Replace('-', '_')
    $lines.Add("  ${jobId}:")
    $lines.Add("    name: '$($manifest.name)'")
    $lines.Add('    runs-on: ubuntu-latest')
    $needs = @('select') + @($manifest.prerequisites | ForEach-Object { 'module_' + $_.Replace('-', '_') })
    $lines.Add("    needs: [$($needs -join ', ')]")
    $condition = "!cancelled() && needs.select.result == 'success' && contains(fromJSON(needs.select.outputs.modules), '$($manifest.name)')"
    foreach ($prerequisite in $manifest.prerequisites) {
        $condition += " && needs.module_$($prerequisite.Replace('-', '_')).result == 'success'"
    }
    $lines.Add('    if: ${{ ' + $condition + ' }}')
    $lines.Add("    environment: $($manifest.name)-plan")
    $lines.Add('    steps:')
    $lines.Add('      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262')
    $lines.Add('      - name: Install runtime dependencies')
    $lines.Add('        shell: pwsh')
    $lines.Add('        run: ./platform/tools/Install-ToolDependencies.ps1')
    $lines.Add('      - name: Run module')
    $lines.Add('        shell: pwsh')
    $lines.Add("        run: ./platform/tools/Invoke-Module.ps1 -Module '$($manifest.name)' -Action plan -InstancePath ./instance.yaml")
}

$fullOutputPath = [System.IO.Path]::GetFullPath($OutputPath)
$content = ($lines -join "`n") + "`n"
$encoding = [System.Text.UTF8Encoding]::new($false)
if ($Check) {
    if (-not (Test-Path -LiteralPath $fullOutputPath -PathType Leaf) -or
        [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($fullOutputPath)) -cne
        [Convert]::ToBase64String($encoding.GetBytes($content))) {
        throw "Generated workflow differs from '$OutputPath'. Run tools/Generate-DeploymentWorkflow.ps1 to regenerate it."
    }
    return
}
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($fullOutputPath)) | Out-Null
[System.IO.File]::WriteAllText($fullOutputPath, $content, $encoding)
